// Revue du lot « interface multilingue » (2026-10-14) : bloquants B1 et B2, et les mineurs corriges avec eux.
// Prouve, avec le VRAI i18n.js et les VRAIS dictionnaires de chaque cible (charges dans l'ordre de la page), dans un DOM
// minimal (tests/_dom-minimal.mjs) — aucun navigateur, aucun reseau :
//  B1. le texte indicatif « What is wrong with this result? » du formulaire de signalement (Store 11.16) est traduit
//      dans les 5 langues, sur le web et sur le bureau (il restait en anglais en es, zh, hi, ar) ;
//  B2. TOUS les textes de plus de 200 caracteres que montre l'interface (avertissement IA de la fenetre A propos, textes
//      de vie privee des Reglages, bulles des options 3D…) sont traduits dans les 5 langues ;
//  et : les etats du formulaire de signalement poses par textContent sont traduits ; « 48&nbsp;h » trouve son entree ;
//  en arabe, la pipette ne recoit plus de caracteres d'isolation (le bouton « Copy HEX » copiait « #a1b2c3 » entoure de U+2068 / U+2069) ;
//  un nom choisi par l'utilisateur apres « Export failed: » garde son texte ; « HTTP 503: <message> » est traduit.
// Lancer : cd cloud && node --test tests/revue-interface-langue.test.mjs
// Preuve sur l'ancien code : RACINE_DEPOT=<copie de b2d4bb70> node --test tests/revue-interface-langue.test.mjs
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { creerPage } from './_dom-minimal.mjs';
import { zoneHtml } from '../../build/check-traductions.mjs';
import { CIBLES, fichiersCible, libellesCible, estNeutre } from '../../build/couverture-traductions.mjs';

const RACINE = process.env.RACINE_DEPOT || path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const lire = (rel) => fs.readFileSync(path.join(RACINE, rel), 'utf8');
const LANGUES = ['fr', 'es', 'zh', 'hi', 'ar'];
const BASE = { web: 'cloud/public/app', bureau: 'src/renderer' };
const PAGE = { web: 'cloud/public/app/index.html', bureau: 'src/renderer/index2.html' };
const ISOLATION = /[\u2066-\u2069]/;
const echapper = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Page avec le VRAI i18n.js, les VRAIS lang/*.js et lib/textes-serveur.js de la cible, dans l'ordre de sa page. */
function page(cible, lang, html = '<div id="zone"></div>') {
  const p = creerPage({ html, stockage: { 'fabmesh.lang.choisi': lang } });
  p.executer(lire(BASE[cible] + '/i18n.js'), 'i18n.js');
  for (const m of lire(PAGE[cible]).matchAll(/<script src="(lang\/[^"]+|lib\/textes-serveur\.js)"><\/script>/g)) p.executer(lire(BASE[cible] + '/' + m[1]), m[1]);
  p.charger();
  return p;
}

for (const cible of ['web', 'bureau']) {
  test(`${cible} : B1 — le texte indicatif du formulaire de signalement est traduit dans les 5 langues`, async () => {
    const zone = zoneHtml(lire(PAGE[cible]), 'modal-report');
    assert.ok(zone && zone.includes('id="rp-details"'), 'formulaire de signalement introuvable');
    const ANGLAIS = 'What is wrong with this result?';
    for (const L of LANGUES) {
      const p = page(cible, L, zone);
      await p.attendre();
      assert.equal(p.fenetre.FabI18n.lang, L);
      const ph = p.document.getElementById('rp-details').getAttribute('placeholder');
      assert.notEqual(ph, ANGLAIS, `${cible}/${L} : texte indicatif reste en anglais`);
      assert.ok(!ISOLATION.test(ph), `${cible}/${L} : ${JSON.stringify(ph)}`);
    }
  });

  test(`${cible} : B2 — chaque texte de PLUS DE 200 caracteres de l'interface est traduit dans les 5 langues`, async () => {
    const c = CIBLES.find((x) => x.nom === cible);
    const longs = [...libellesCible(fichiersCible(RACINE, c)).keys()].filter((k) => k.length > 200 && !estNeutre(k));
    assert.ok(longs.length >= 8, `${cible} : ${longs.length} textes longs seulement (extraction ?)`);
    // l'avertissement de la fenetre A propos (point d'entree 11.16 de l'examinateur) en fait partie
    assert.ok(longs.some((k) => k.startsWith('Results are generated by AI models')), 'avertissement IA absent de la mesure');
    const html = longs.map((k, i) => `<p id="long-${i}">${echapper(k)}</p>`).join('');
    for (const L of LANGUES) {
      const p = page(cible, L, html);
      await p.attendre();
      const restes = longs.filter((k, i) => {
        const v = p.document.getElementById('long-' + i).textContent;
        return v === k || ISOLATION.test(v);
      });
      assert.deepEqual(restes.map((k) => k.slice(0, 70)), [], `${cible}/${L} : textes longs restes en anglais`);
    }
  });

  test(`${cible} : etats du formulaire de signalement et bulles posees par le code (textContent / title) traduits`, async () => {
    const TEXTES = ['Sending your report…', 'Report sent. Thank you — an admin will review it.', 'Content deleted. Your report was kept.',
      'Could not reach the server — your e-mail app has been opened instead.', 'Could not reach the server. Please e-mail your report to ', 'Copy address', 'Sent'];
    for (const L of LANGUES) {
      const p = page(cible, L, '<div id="etat"></div><button id="b"></button>');
      await p.attendre();
      const etat = p.document.getElementById('etat');
      for (const t of TEXTES) {
        etat.textContent = t;          // comme index2.js : l'observateur du traducteur voit le noeud ajoute
        await p.attendre();
        assert.notEqual(etat.textContent.trim(), t.trim(), `${cible}/${L} : ${t}`);
        assert.ok(!ISOLATION.test(etat.textContent), `${cible}/${L} : ${t}`);
      }
      const b = p.document.getElementById('b');
      for (const t of ['red', 'Enter the exact value', 'Generate a rig first']) {
        b.title = t;
        await p.attendre();
        assert.notEqual(b.getAttribute('title'), t, `${cible}/${L} : title ${t}`);
      }
    }
  });

  test(`${cible} : un texte ecrit avec &nbsp; (« 48&nbsp;h ») trouve son entree, comme un texte a espaces ordinaires`, async () => {
    const ANGLAIS = 'We read every message · usually reply within 48\u00a0h';
    for (const L of LANGUES) {
      const p = page(cible, L, `<div id="n">${ANGLAIS}</div>`);
      await p.attendre();
      const v = p.document.getElementById('n').textContent;
      assert.notEqual(v, ANGLAIS, `${cible}/${L}`);
      assert.ok(!ISOLATION.test(v), `${cible}/${L} : ${JSON.stringify(v)}`);
    }
  });

  test(`${cible} : arabe — la pipette garde « #a1b2c3 » tel quel (pas de caracteres d'isolation dans ce que copie Copy HEX)`, async () => {
    const zone = zoneHtml(lire(PAGE[cible]), 'modal-colorpick');
    assert.ok(zone && zone.includes('id="cpick-hex"'), 'pipette introuvable');
    const p = page(cible, 'ar', zone);
    await p.attendre();
    assert.equal(p.fenetre.FabI18n.rtl, true);
    const hex = p.document.getElementById('cpick-hex');
    const rgb = p.document.getElementById('cpick-rgb');
    hex.textContent = '#a1b2c3';     // comme _cpSample (index2.js)
    rgb.textContent = 'rgb(161, 178, 195)';
    await p.attendre();
    assert.equal(hex.textContent, '#a1b2c3');
    assert.equal(rgb.textContent, 'rgb(161, 178, 195)');
    assert.equal(hex.getAttribute('dir'), 'ltr', 'valeur affichee de gauche a droite');
  });

  test(`${cible} : refus du serveur — un NOM d'un mot apres « Prefixe: » garde son texte ; « HTTP 503: <message> » est traduit`, async () => {
    for (const L of ['es', 'fr', 'ar']) {
      const fm = page(cible, L).fenetre.FabMessages;
      const ex = fm.traduire('Export failed: Settings');
      assert.notEqual(ex, 'Export failed: Settings', `${L} : le prefixe doit etre traduit`);
      assert.ok(/Settings/.test(ex), `${L} : le nom choisi par l'utilisateur a change : ${ex}`);
      // les refus d'un mot passent toujours par leur code
      assert.ok(!/unauthorized/.test(fm.traduire('Failed: unauthorized')), L);
      const MSG = 'Cloud generation is paused for now — your credits are safe and you were not charged. Please try again later.';
      const h = fm.traduire('HTTP 503: ' + MSG);
      assert.ok(h.startsWith('HTTP 503: '), `${L} : ${h}`);
      assert.ok(!h.includes('Cloud generation is paused'), `${L} : message reste en anglais : ${h}`);
      assert.equal(fm.traduire('HTTP 404: zorglub'), 'HTTP 404: zorglub', 'message inconnu : texte d origine');
    }
    assert.equal(page(cible, 'en').fenetre.FabMessages.traduire('HTTP 503: anything'), 'HTTP 503: anything');
  });
}
